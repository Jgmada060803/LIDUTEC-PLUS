insert into public.permissoes(codigo,nome,descricao,modulo,ativo)
select codigo,nome,descricao,'PRODUCAO',true from (values
  ('producao_acabamento.visualizar','Visualizar produção de acabamento','Consulta produção, paradas e indicadores do acabamento.'),
  ('producao_acabamento.lancar','Lançar produção de acabamento','Registra produção e paradas do acabamento.'),
  ('producao_acabamento.editar','Editar produção de acabamento','Corrige registros de produção e paradas do acabamento.'),
  ('producao_acabamento.excluir_turno','Excluir turno de acabamento','Exclui integralmente um turno fechado de acabamento e seus apontamentos.')
) permission(codigo,nome,descricao)
where not exists(select 1 from public.permissoes current_permission
  where current_permission.codigo=permission.codigo);

insert into public.perfil_permissoes(perfil_id,permissao_id)
select profile.id,permission.id from public.perfis profile
cross join public.permissoes permission
where (upper(profile.codigo) in ('ADMIN','ADMINISTRADOR')
  or upper(profile.nome)='ADMINISTRADOR')
and permission.codigo like 'producao_acabamento.%'
and not exists(select 1 from public.perfil_permissoes relation
  where relation.perfil_id=profile.id and relation.permissao_id=permission.id);

insert into public.perfil_permissoes(perfil_id,permissao_id)
select perfil.id,permissao.id from public.perfis perfil
join public.permissoes permissao on permissao.codigo='producao_acabamento.excluir_turno'
where upper(coalesce(perfil.codigo,'')) in ('GERENTE_PRODUCAO','COORDENADOR_PRODUCAO')
on conflict do nothing;

create or replace function public.usuario_tem_permissao_producao_acabamento(p_codigo text)
returns boolean language sql stable security definer
set search_path=pg_catalog,public as $$
  select auth.uid() is not null and coalesce(
    (select user_permission.permitido
     from public.usuario_permissoes user_permission
     join public.permissoes permission on permission.id=user_permission.permissao_id
     where user_permission.usuario_id=auth.uid()
       and permission.codigo=p_codigo limit 1),
    exists(select 1 from public.usuario_perfis user_profile
      join public.perfil_permissoes profile_permission
        on profile_permission.perfil_id=user_profile.perfil_id
      join public.permissoes permission
        on permission.id=profile_permission.permissao_id
      where user_profile.usuario_id=auth.uid() and permission.codigo=p_codigo)
  );
$$;
grant execute on function public.usuario_tem_permissao_producao_acabamento(text) to authenticated;

