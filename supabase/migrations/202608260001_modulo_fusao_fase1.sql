-- Abre um novo ciclo pro forno (trocou o refratário), encerrando o anterior
-- se existir. Se for a primeira vez do forno, só abre o ciclo 1.
create or replace function public.trocar_refratario_fusao(p_forno_id bigint, p_motivo text default null)
returns bigint language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_novo_numero integer; v_id bigint;
begin
  if not public.usuario_tem_permissao_producao_fusao('producao_fusao.lancar') then
    raise exception 'Usuário sem permissão para registrar troca de refratário.';
  end if;
  update public.ciclos_refratario_fusao set encerrado_em=now(), motivo_encerramento=nullif(trim(p_motivo),'')
  where forno_id=p_forno_id and encerrado_em is null;
  select coalesce(max(numero_ciclo),0)+1 into v_novo_numero from public.ciclos_refratario_fusao where forno_id=p_forno_id;
  insert into public.ciclos_refratario_fusao(forno_id,numero_ciclo,iniciado_por)
  values(p_forno_id,v_novo_numero,auth.uid()) returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.trocar_refratario_fusao(bigint,text) from public,anon;
grant execute on function public.trocar_refratario_fusao(bigint,text) to authenticated;

