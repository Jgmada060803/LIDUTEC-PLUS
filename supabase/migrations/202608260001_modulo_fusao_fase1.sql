-- ==========================================================================
-- RPCs de apontamento — 1 ação por papel, sem rascunho compartilhado (ver
-- comentário no topo do arquivo).
-- ==========================================================================

-- Supervisor: cria a corrida com a carga planejada. Usa o ciclo de
-- refratário aberto do forno (cria o ciclo 1 automaticamente se o forno
-- nunca teve nenhum). Trava a linha do ciclo pra gerar a sequência sem
-- risco de 2 corridas nascerem com o mesmo número.
create or replace function public.criar_corrida_fusao(
  p_forno_id bigint, p_turno text, p_itens jsonb
) returns bigint language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_ciclo record;
  v_forno record;
  v_sequencia integer;
  v_codigo text;
  v_corrida_id bigint;
begin
  if not public.usuario_tem_permissao_producao_fusao('producao_fusao.lancar') then
    raise exception 'Usuário sem permissão para lançar produção de fusão.';
  end if;
  if p_turno not in ('MANHA','TARDE','NOITE') then raise exception 'Turno inválido.'; end if;
  if jsonb_array_length(coalesce(p_itens,'[]'::jsonb)) = 0 then raise exception 'Informe ao menos um material na carga.'; end if;

  select * into v_forno from public.fornos_fusao where id = p_forno_id and tipo = 'FUSAO' for update;
  if not found then raise exception 'Forno inválido.'; end if;

  select * into v_ciclo from public.ciclos_refratario_fusao where forno_id = p_forno_id and encerrado_em is null for update;
  if not found then
    insert into public.ciclos_refratario_fusao(forno_id, numero_ciclo, iniciado_por)
    values (p_forno_id, 1, auth.uid())
    returning * into v_ciclo;
  end if;

  select coalesce(max(numero_sequencia), 0) + 1 into v_sequencia
  from public.corridas_fusao where ciclo_refratario_id = v_ciclo.id;
  v_codigo := v_forno.codigo || lpad(v_ciclo.numero_ciclo::text, 3, '0') || lpad(v_sequencia::text, 3, '0');

  insert into public.corridas_fusao(forno_id, ciclo_refratario_id, numero_sequencia, codigo, data_operacional, turno, criado_por, atualizado_por)
  values (p_forno_id, v_ciclo.id, v_sequencia, v_codigo, current_date, p_turno, auth.uid(), auth.uid())
  returning id into v_corrida_id;

  insert into public.corridas_fusao_carga_itens(corrida_id, material_id, quantidade_planejada_kg)
  select v_corrida_id, item.material_id, item.quantidade_planejada_kg
  from jsonb_to_recordset(p_itens) as item(material_id bigint, quantidade_planejada_kg numeric)
  where item.material_id is not null and item.quantidade_planejada_kg >= 0;

  return v_corrida_id;
end;
$$;
revoke all on function public.criar_corrida_fusao(bigint,text,jsonb) from public,anon;
grant execute on function public.criar_corrida_fusao(bigint,text,jsonb) to authenticated;

-- Operador da ponte: registra o realizado de 1 material por vez — não
-- conflita com o planejamento (coluna diferente) nem com outro material
-- sendo pesado ao mesmo tempo (linha diferente).
create or replace function public.atualizar_pesagem_carga_fusao(
  p_corrida_id bigint, p_material_id bigint, p_quantidade_realizada_kg numeric
) returns void language plpgsql security definer set search_path=pg_catalog,public as $$
begin
  if not public.usuario_tem_permissao_producao_fusao('producao_fusao.lancar') then
    raise exception 'Usuário sem permissão para lançar produção de fusão.';
  end if;
  if p_quantidade_realizada_kg is not null and p_quantidade_realizada_kg < 0 then
    raise exception 'Quantidade realizada não pode ser negativa.';
  end if;
  update public.corridas_fusao_carga_itens
  set quantidade_realizada_kg = p_quantidade_realizada_kg, atualizado_por = auth.uid(), atualizado_em = now()
  where corrida_id = p_corrida_id and material_id = p_material_id;
  if not found then raise exception 'Item de carga não encontrado nesta corrida.'; end if;
end;
$$;
revoke all on function public.atualizar_pesagem_carga_fusao(bigint,bigint,numeric) from public,anon;
grant execute on function public.atualizar_pesagem_carga_fusao(bigint,bigint,numeric) to authenticated;

