-- Fornos de elaboração (tipo FUSAO) e Holdings (tipo HOLDING, só recebem/
-- mantêm — usados na Fase 2). Limites de corridas do refratário ficam aqui,
-- por forno, pra dar pra ajustar sem mexer em código.
create table if not exists public.fornos_fusao (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nome text not null,
  tipo text not null check (tipo in ('FUSAO','HOLDING')),
  limite_atencao_corridas integer not null default 100,
  limite_critico_corridas integer not null default 150,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  check (limite_critico_corridas >= limite_atencao_corridas)
);
alter table public.fornos_fusao enable row level security;
drop policy if exists fornos_fusao_select on public.fornos_fusao;
