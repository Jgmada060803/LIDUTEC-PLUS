create or replace function public.salvar_material_fusao(
  p_id bigint, p_codigo text, p_nome text, p_tipo text, p_ativo boolean default true
) returns bigint language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_id bigint;
begin
  if not public.usuario_tem_permissao_producao_fusao('producao_fusao.configurar') then
    raise exception 'Usuário sem permissão para configurar cadastros de fusão.';
  end if;
  if p_tipo not in ('SUCATA','RETORNO','CANAL','LIGA_CORRECAO','OUTRO') then raise exception 'Tipo de material inválido.'; end if;
  if p_id is null then
    insert into public.materiais_fusao(codigo,nome,tipo,ativo) values(trim(p_codigo),trim(p_nome),p_tipo,coalesce(p_ativo,true))
    returning id into v_id;
  else
    update public.materiais_fusao set codigo=trim(p_codigo),nome=trim(p_nome),tipo=p_tipo,ativo=coalesce(p_ativo,true)
    where id=p_id returning id into v_id;
  end if;
  return v_id;
end;
$$;
revoke all on function public.salvar_material_fusao(bigint,text,text,text,boolean) from public,anon;
grant execute on function public.salvar_material_fusao(bigint,text,text,text,boolean) to authenticated;

