-- Avança (ou cancela) o status da corrida — única ação com trava de versão,
-- pra 2 cliques simultâneos em "concluir etapa" não pularem 2 estados.
create or replace function public.avancar_status_corrida_fusao(
  p_corrida_id bigint, p_novo_status text, p_versao bigint
) returns void language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_corrida record;
  v_ordem text[] := array['PLANEJADA','CARREGANDO','ELABORACAO','PRONTA','TRANSFERIDA'];
  v_atual_pos integer; v_novo_pos integer;
begin
  if not public.usuario_tem_permissao_producao_fusao('producao_fusao.lancar') then
    raise exception 'Usuário sem permissão para lançar produção de fusão.';
  end if;
  select * into v_corrida from public.corridas_fusao where id = p_corrida_id for update;
  if not found then raise exception 'Corrida não encontrada.'; end if;
  if v_corrida.versao <> p_versao then
    raise exception 'CONFLITO_RASCUNHO: a corrida foi atualizada por outro usuário.' using errcode = '40001';
  end if;
  if v_corrida.status in ('TRANSFERIDA','CANCELADA') then
    raise exception 'Esta corrida já foi encerrada.';
  end if;
  if p_novo_status = 'CANCELADA' then
    update public.corridas_fusao set status='CANCELADA', versao=versao+1, atualizado_por=auth.uid(), atualizado_em=now()
    where id = p_corrida_id;
    return;
  end if;
  v_atual_pos := array_position(v_ordem, v_corrida.status);
  v_novo_pos := array_position(v_ordem, p_novo_status);
  if v_novo_pos is null or v_novo_pos <> v_atual_pos + 1 then
    raise exception 'Transição de status inválida (% -> %).', v_corrida.status, p_novo_status;
  end if;
  update public.corridas_fusao set status = p_novo_status, versao = versao + 1, atualizado_por = auth.uid(), atualizado_em = now()
  where id = p_corrida_id;
end;
$$;
revoke all on function public.avancar_status_corrida_fusao(bigint,text,bigint) from public,anon;
grant execute on function public.avancar_status_corrida_fusao(bigint,text,bigint) to authenticated;

notify pgrst, 'reload schema';

