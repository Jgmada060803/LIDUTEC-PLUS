begin;

-- ==========================================================================
-- Módulo de Fusão — Fase 1 (planejamento da carga até a corrida "pronta"
-- pra transferência; Holding/panela/vazamento ficam pra uma Fase 2).
--
-- Vários papéis mexem na MESMA corrida ao mesmo tempo (supervisor planeja,
-- operador da ponte pesa, operador do forno registra adição e avança
-- status) — por isso, ao contrário das telas de turno (Moldagem/Acabamento/
-- Macharia, que usam 1 rascunho JSON com versão), aqui cada ação vira uma
-- RPC pequena e independente, mexendo só na própria linha/coluna. Só a
-- transição de status da corrida usa "versao" (trava optimista), pra dois
-- cliques simultâneos em "concluir" não avançarem duas vezes.
-- ==========================================================================

insert into public.permissoes(codigo,nome,descricao,modulo,ativo)
select codigo,nome,descricao,'PRODUCAO',true from (values
  ('producao_fusao.visualizar','Visualizar produção de fusão','Consulta corridas, cargas e indicadores da Fusão.'),
  ('producao_fusao.lancar','Lançar produção de fusão','Planeja carga, registra pesagem, adições e avança o status da corrida.'),
  ('producao_fusao.editar','Editar produção de fusão','Corrige registros de uma corrida já concluída ou cancela uma corrida.'),
  ('producao_fusao.configurar','Configurar cadastros de fusão','Cadastra materiais, fornos e troca de refratário.')
) permission(codigo,nome,descricao)
where not exists(select 1 from public.permissoes current_permission
  where current_permission.codigo=permission.codigo);

insert into public.perfil_permissoes(perfil_id,permissao_id)
select profile.id,permission.id from public.perfis profile
cross join public.permissoes permission
where (upper(profile.codigo) in ('ADMIN','ADMINISTRADOR') or upper(profile.nome)='ADMINISTRADOR')
and permission.codigo like 'producao_fusao.%'
and not exists(select 1 from public.perfil_permissoes relation
  where relation.perfil_id=profile.id and relation.permissao_id=permission.id);

insert into public.perfil_permissoes(perfil_id,permissao_id)
select perfil.id,permissao.id from public.perfis perfil
join public.permissoes permissao on permissao.codigo in ('producao_fusao.visualizar','producao_fusao.lancar')
where upper(coalesce(perfil.codigo,'')) in ('FUSAO','COORDENADOR_PRODUCAO','GERENTE_PRODUCAO')
on conflict do nothing;

insert into public.perfil_permissoes(perfil_id,permissao_id)
select perfil.id,permissao.id from public.perfis perfil
join public.permissoes permissao on permissao.codigo in ('producao_fusao.editar','producao_fusao.configurar')
where upper(coalesce(perfil.codigo,'')) in ('COORDENADOR_PRODUCAO','GERENTE_PRODUCAO')
on conflict do nothing;

-- Mesmo corpo usado em todos os domínios de produção (ver
-- usuario_tem_permissao_producao_macharia/acabamento).
create or replace function public.usuario_tem_permissao_producao_fusao(p_codigo text)
returns boolean language sql stable security definer
set search_path=pg_catalog,public as $$
  select auth.uid() is not null and coalesce(
    (select user_permission.permitido
     from public.usuario_permissoes user_permission
     join public.permissoes permission on permission.id=user_permission.permissao_id
     where user_permission.usuario_id=auth.uid()
       and permission.codigo=p_codigo limit 1),
    exists(select 1 from public.usuario_perfis user_profile
      join public.perfil_permissoes profile_permission
        on profile_permission.perfil_id=user_profile.perfil_id
      join public.permissoes permission
        on permission.id=profile_permission.permissao_id
      where user_profile.usuario_id=auth.uid() and permission.codigo=p_codigo)
  );
$$;

