  public.usuario_tem_permissao_producao_macharia('producao_macharia.visualizar'));
grant select on public.historico_edicoes_turno_macharia to authenticated;

grant usage,select on sequence
  public.turnos_producao_macharia_id_seq,
  public.registros_producao_macharia_id_seq,
  public.historico_edicoes_turno_macharia_id_seq
to authenticated;

