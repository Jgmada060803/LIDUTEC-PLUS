insert into public.permissoes(codigo,nome,descricao,modulo,ativo)
select codigo,nome,descricao,'PRODUCAO',true from (values
  ('producao_macharia.visualizar','Visualizar produção de macharia','Consulta apontamentos e indicadores de macharia.'),
  ('producao_macharia.lancar','Lançar produção de macharia','Registra sopros por estação de macharia.'),
  ('producao_macharia.editar','Editar produção de macharia','Corrige registros de um turno fechado de macharia.'),
  ('producao_macharia.excluir_turno','Excluir turno de macharia','Exclui integralmente um turno fechado de macharia e seus apontamentos.')
) permission(codigo,nome,descricao)
where not exists(select 1 from public.permissoes current_permission
  where current_permission.codigo=permission.codigo);

insert into public.perfil_permissoes(perfil_id,permissao_id)
select profile.id,permission.id from public.perfis profile
cross join public.permissoes permission
where (upper(profile.codigo) in ('ADMIN','ADMINISTRADOR')
  or upper(profile.nome)='ADMINISTRADOR')
and permission.codigo like 'producao_macharia.%'
and not exists(select 1 from public.perfil_permissoes relation
  where relation.perfil_id=profile.id and relation.permissao_id=permission.id);

insert into public.perfil_permissoes(perfil_id,permissao_id)
select perfil.id,permissao.id from public.perfis perfil
join public.permissoes permissao on permissao.codigo='producao_macharia.excluir_turno'
where upper(coalesce(perfil.codigo,'')) in ('GERENTE_PRODUCAO','COORDENADOR_PRODUCAO')
on conflict do nothing;

-- ==========================================================================
-- Tabelas
-- ==========================================================================
create table if not exists public.turnos_producao_macharia (
  id bigint generated by default as identity primary key,
  data_operacional date not null,
  turno text not null check (turno in ('MANHA','TARDE','NOITE')),
  status text not null default 'ABERTO' check (status in ('ABERTO','FECHADO')),
  fechado_por uuid references public.usuarios(id),
  fechado_em timestamptz,
  criado_por uuid not null default auth.uid() references public.usuarios(id),
  criado_em timestamptz not null default now(),
  rascunho_producoes jsonb not null default '[]'::jsonb,
  versao bigint not null default 0,
  atualizado_por uuid references public.usuarios(id),
  atualizado_em timestamptz,
  unique (data_operacional, turno),
  check ((status='ABERTO' and fechado_em is null) or
         (status='FECHADO' and fechado_em is not null and fechado_por is not null))
);

do $$ begin
  if not exists(select 1 from pg_catalog.pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='turnos_producao_macharia') then
    alter publication supabase_realtime add table public.turnos_producao_macharia;
  end if;
end $$;

-- Uma linha por sopro lançado numa estação/hora — máquina e estação em vez de
-- produto (o produto é resolvido depois, via machos_macharia_produtos).
create table if not exists public.registros_producao_macharia (
  id bigint generated by default as identity primary key,
  turno_producao_id bigint not null references public.turnos_producao_macharia(id),
  linha_maquina_id bigint not null references public.linhas_maquinas_producao(id),
  estacao integer not null check (estacao > 0),
  data_operacional date not null,
  turno text not null check (turno in ('MANHA','TARDE','NOITE')),
  horario_previsto timestamptz not null,
  macho_id bigint not null references public.machos_macharia(id),
  quantidade_sopros integer not null default 0 check (quantidade_sopros>=0),
  criado_por uuid not null default auth.uid() references public.usuarios(id),
  criado_em timestamptz not null default now()
);

create index if not exists registros_macharia_turno_idx
  on public.registros_producao_macharia(turno_producao_id);
create index if not exists registros_macharia_data_turno_idx
  on public.registros_producao_macharia(data_operacional desc, turno);
create index if not exists registros_macharia_linha_idx
  on public.registros_producao_macharia(linha_maquina_id, estacao, horario_previsto);

create table if not exists public.historico_edicoes_turno_macharia (
  id bigint generated by default as identity primary key,
  turno_producao_id bigint not null references public.turnos_producao_macharia(id) on delete cascade,
  descricao text not null check (length(trim(descricao)) between 1 and 1000),
  dados_anteriores jsonb not null default '{}'::jsonb,
  dados_novos jsonb not null default '{}'::jsonb,
  alterado_por uuid not null default auth.uid() references public.usuarios(id),
  alterado_em timestamptz not null default now()
);

create index if not exists historico_edicoes_turno_macharia_idx
  on public.historico_edicoes_turno_macharia(turno_producao_id, alterado_em desc);

