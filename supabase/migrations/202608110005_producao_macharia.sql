create or replace function public.validar_acesso_producao_macharia()
returns trigger language plpgsql security definer set search_path=pg_catalog,public as $$
begin
  if not public.usuario_pode_acessar_area_codigo('MACHARIA') then
    raise exception 'Usuário sem acesso à área de Macharia.';
  end if;
  return new;
end $$;

drop trigger if exists validar_area_turno_macharia on public.turnos_producao_macharia;
create trigger validar_area_turno_macharia before insert or update on public.turnos_producao_macharia
for each row execute function public.validar_acesso_producao_macharia();
drop trigger if exists validar_area_registro_macharia on public.registros_producao_macharia;
create trigger validar_area_registro_macharia before insert or update on public.registros_producao_macharia
for each row execute function public.validar_acesso_producao_macharia();

