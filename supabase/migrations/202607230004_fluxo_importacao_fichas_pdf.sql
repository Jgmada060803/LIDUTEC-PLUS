create or replace function public.usuario_tem_permissao_ficha(
  p_codigo text
)
returns boolean
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_usuario_id uuid := auth.uid();
  v_permitido_individual boolean;
begin
  if v_usuario_id is null then
    return false;
  end if;

  select usuario_permissao.permitido
    into v_permitido_individual
  from public.usuario_permissoes usuario_permissao
  join public.permissoes permissao
    on permissao.id = usuario_permissao.permissao_id
  where usuario_permissao.usuario_id = v_usuario_id
    and permissao.codigo = p_codigo
  limit 1;

  if found then
    return coalesce(v_permitido_individual, false);
  end if;

  return exists (
    select 1
    from public.usuario_perfis usuario_perfil
    join public.perfil_permissoes perfil_permissao
      on perfil_permissao.perfil_id = usuario_perfil.perfil_id
    join public.permissoes permissao
      on permissao.id = perfil_permissao.permissao_id
    where usuario_perfil.usuario_id = v_usuario_id
      and permissao.codigo = p_codigo
  );
end;
$$;

revoke all on function public.usuario_tem_permissao_ficha(text)
  from public;
grant execute on function public.usuario_tem_permissao_ficha(text)
  to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_catalog.pg_policies
    where schemaname = 'public'
      and tablename = 'templates_importacao_ficha'
      and policyname = 'templates_importacao_select'
  ) then
    create policy templates_importacao_select
      on public.templates_importacao_ficha for select
      to authenticated
      using (
        auth.uid() is not null
        and public.usuario_tem_permissao_ficha('ficha.visualizar')
      );
  end if;

  if not exists (
    select 1 from pg_catalog.pg_policies
    where schemaname = 'public'
      and tablename = 'importacoes_ficha'
      and policyname = 'importacoes_ficha_select'
  ) then
    create policy importacoes_ficha_select
      on public.importacoes_ficha for select
      to authenticated
      using (
        auth.uid() is not null
        and (
          public.usuario_tem_permissao_ficha('ficha.visualizar')
          or public.usuario_tem_permissao_ficha('ficha.importar')
          or public.usuario_tem_permissao_ficha(
            'ficha.conferir_importacao'
          )
          or public.usuario_tem_permissao_ficha(
            'ficha.validar_importacao'
          )
        )
      );
  end if;

  if not exists (
    select 1 from pg_catalog.pg_policies
    where schemaname = 'public'
      and tablename = 'validacoes_importacao_ficha'
      and policyname = 'validacoes_importacao_select'
  ) then
    create policy validacoes_importacao_select
      on public.validacoes_importacao_ficha for select
      to authenticated
      using (
        auth.uid() is not null
        and public.usuario_tem_permissao_ficha('ficha.visualizar')
      );
  end if;

  if not exists (
    select 1 from pg_catalog.pg_policies
    where schemaname = 'public'
      and tablename = 'auditoria_importacao_ficha'
      and policyname = 'auditoria_importacao_select'
  ) then
    create policy auditoria_importacao_select
      on public.auditoria_importacao_ficha for select
      to authenticated
      using (
        auth.uid() is not null
        and (
          public.usuario_tem_permissao_ficha(
            'ficha.conferir_importacao'
          )
          or public.usuario_tem_permissao_ficha(
            'ficha.validar_importacao'
          )
        )
      );
  end if;
end;
$$;

