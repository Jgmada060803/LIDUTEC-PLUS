create or replace function public.registrar_fonte_medicao_checklist()
returns trigger language plpgsql security definer set search_path=pg_catalog,public as $$
declare item public.itens_checklist; doc_codigo text;
begin
 select * into item from public.itens_checklist where id=new.item_id;
 if item.fonte_limite_tipo='INSTRUCAO_TRABALHO' then
  select instrucao.codigo into doc_codigo from public.especificacoes_instrucao_trabalho spec
  join public.revisoes_instrucao_trabalho revisao on revisao.id=spec.revisao_id
  join public.instrucoes_trabalho instrucao on instrucao.id=revisao.instrucao_id
  where spec.id=item.fonte_limite_id;
 end if;
 new.fonte_limite_tipo:=item.fonte_limite_tipo;
 new.fonte_limite_id:=item.fonte_limite_id;
 new.fonte_limite_codigo:=doc_codigo;
 new.fonte_limite_revisao:=item.fonte_limite_revisao;
 new.fonte_limite_pagina:=item.fonte_limite_pagina;
 return new;
end $$;
