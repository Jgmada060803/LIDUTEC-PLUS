create or replace function public.salvar_revisao_instrucao_trabalho(
 p_codigo text,p_titulo text,p_area_id bigint,p_revisao text,p_caminho_arquivo text,
 p_hash_arquivo text,p_observacao text,p_especificacoes jsonb
) returns bigint language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_instrucao_id bigint; v_revisao_id bigint; e jsonb;
begin
 if not (public.usuario_tem_permissao_ficha('ficha.criar') or public.usuario_tem_permissao_ficha('ficha.editar_rascunho')) then raise exception 'Usuário sem permissão para gerenciar IT.'; end if;
 if nullif(trim(p_codigo),'') is null or nullif(trim(p_revisao),'') is null or nullif(trim(p_caminho_arquivo),'') is null then
  raise exception 'Código, revisão e caminho do PDF são obrigatórios.';
 end if;
 if p_hash_arquivo is not null and exists(select 1 from public.revisoes_instrucao_trabalho where hash_arquivo=p_hash_arquivo) then
  raise exception 'Este mesmo arquivo PDF já foi cadastrado.';
 end if;
 insert into public.instrucoes_trabalho(codigo,titulo,area_id) values(upper(trim(p_codigo)),trim(p_titulo),p_area_id)
 on conflict(codigo) do update set titulo=excluded.titulo,area_id=excluded.area_id,ativo=true returning id into v_instrucao_id;
 insert into public.revisoes_instrucao_trabalho(instrucao_id,revisao,caminho_arquivo,hash_arquivo,observacao)
 values(v_instrucao_id,trim(p_revisao),trim(p_caminho_arquivo),nullif(trim(p_hash_arquivo),''),nullif(trim(p_observacao),'')) returning id into v_revisao_id;
 for e in select value from jsonb_array_elements(coalesce(p_especificacoes,'[]'::jsonb)) loop
  insert into public.especificacoes_instrucao_trabalho(revisao_id,chave_parametro,descricao,produto_id,equipamento,
   valor_minimo,valor_alvo,valor_maximo,unidade,frequencia_minutos,pagina,trecho_origem,criticidade,plano_reacao,conferido)
  values(v_revisao_id,upper(trim(e->>'chave_parametro')),trim(e->>'descricao'),nullif(e->>'produto_id','')::bigint,
   nullif(trim(e->>'equipamento'),''),nullif(e->>'valor_minimo','')::numeric,nullif(e->>'valor_alvo','')::numeric,
   nullif(e->>'valor_maximo','')::numeric,nullif(trim(e->>'unidade'),''),nullif(e->>'frequencia_minutos','')::integer,
   nullif(e->>'pagina','')::integer,nullif(trim(e->>'trecho_origem'),''),coalesce(nullif(e->>'criticidade',''),'NORMAL'),
   nullif(trim(e->>'plano_reacao'),''),coalesce((e->>'conferido')::boolean,false));
 end loop;
 return v_revisao_id;
end $$;

create or replace function public.enviar_instrucao_aprovacao(p_revisao_id bigint)
returns bigint language plpgsql security definer set search_path=pg_catalog,public as $$
begin
 if not (public.usuario_tem_permissao_ficha('ficha.criar') or public.usuario_tem_permissao_ficha('ficha.editar_rascunho')) then raise exception 'Usuário sem permissão.'; end if;
 if exists(select 1 from public.especificacoes_instrucao_trabalho where revisao_id=p_revisao_id and not conferido) then
  raise exception 'Todas as especificações devem ser conferidas antes do envio.';
 end if;
 update public.revisoes_instrucao_trabalho set status='PENDENTE_APROVACAO',etapa_aprovacao='ENGENHARIA',submetido_em=now()
 where id=p_revisao_id and status in('RASCUNHO','REJEITADA');
 if not found then raise exception 'A revisão não pode ser enviada nesta situação.'; end if;
 insert into public.aprovacoes_instrucao_trabalho(revisao_id,etapa,status) values(p_revisao_id,'ENGENHARIA','PENDENTE')
 on conflict(revisao_id,etapa) do update set status='PENDENTE',usuario_id=null,observacao=null,decidido_em=null;
 delete from public.aprovacoes_instrucao_trabalho where revisao_id=p_revisao_id and etapa='PRODUCAO';
 return p_revisao_id;
end $$;

create or replace function public.decidir_instrucao_trabalho(p_revisao_id bigint,p_resultado text,p_observacao text)
returns bigint language plpgsql security definer set search_path=pg_catalog,public as $$
declare r public.revisoes_instrucao_trabalho; permissao text; aprovador_engenharia uuid;
begin
 if p_resultado not in('APROVADA','REJEITADA') then raise exception 'Decisão inválida.'; end if;
 if p_resultado='REJEITADA' and nullif(trim(p_observacao),'') is null then raise exception 'Informe a justificativa.'; end if;
 select * into r from public.revisoes_instrucao_trabalho where id=p_revisao_id and status='PENDENTE_APROVACAO' for update;
 if r.id is null then raise exception 'A IT não está aguardando aprovação.'; end if;
 permissao:=case r.etapa_aprovacao when 'ENGENHARIA' then 'ficha.aprovar_engenharia' else 'ficha.aprovar_producao' end;
 if not public.usuario_tem_permissao_ficha(permissao) then raise exception 'Usuário sem permissão para esta etapa.'; end if;
 select usuario_id into aprovador_engenharia from public.aprovacoes_instrucao_trabalho where revisao_id=r.id and etapa='ENGENHARIA' and status='APROVADA';
 if r.etapa_aprovacao='PRODUCAO' and aprovador_engenharia=auth.uid() then raise exception 'Engenharia e Produção devem ser aprovadas por pessoas diferentes.'; end if;
 update public.aprovacoes_instrucao_trabalho set status=p_resultado,usuario_id=auth.uid(),observacao=nullif(trim(p_observacao),''),decidido_em=now()
 where revisao_id=r.id and etapa=r.etapa_aprovacao;
 if p_resultado='REJEITADA' then
  update public.revisoes_instrucao_trabalho set status='REJEITADA',etapa_aprovacao=null where id=r.id;
 elsif r.etapa_aprovacao='ENGENHARIA' then
  update public.revisoes_instrucao_trabalho set etapa_aprovacao='PRODUCAO' where id=r.id;
  insert into public.aprovacoes_instrucao_trabalho(revisao_id,etapa,status) values(r.id,'PRODUCAO','PENDENTE');
 else
  update public.revisoes_instrucao_trabalho old set status='OBSOLETA' from public.revisoes_instrucao_trabalho current
   where current.id=r.id and old.instrucao_id=current.instrucao_id and old.id<>current.id and old.status='VIGENTE';
  update public.revisoes_instrucao_trabalho set status='VIGENTE',etapa_aprovacao=null,vigente_em=now() where id=r.id;
  update public.itens_checklist item set
   valor_minimo=spec.valor_minimo,valor_alvo=spec.valor_alvo,valor_maximo=spec.valor_maximo,
   unidade=coalesce(spec.unidade,item.unidade),fonte_limite_tipo='INSTRUCAO_TRABALHO',
   fonte_limite_id=spec.id,fonte_limite_revisao=r.revisao,fonte_limite_pagina=spec.pagina
  from public.especificacoes_instrucao_trabalho spec
  where spec.revisao_id=r.id and spec.conferido and item.chave_especificacao=spec.chave_parametro
   and spec.produto_id is null and spec.equipamento is null
   and coalesce(item.fonte_limite_tipo,'INSTRUCAO_TRABALHO')<>'FICHA_TECNICA';
 end if;
 return r.id;
end $$;

create or replace function public.resolver_limite_instrucao_trabalho(p_chave text,p_produto_id bigint default null,p_equipamento text default null)
returns table(especificacao_id bigint,valor_minimo numeric,valor_alvo numeric,valor_maximo numeric,unidade text,
 fonte_codigo text,fonte_revisao text,fonte_pagina integer) language sql stable security definer set search_path=pg_catalog,public as $$
 select e.id,e.valor_minimo,e.valor_alvo,e.valor_maximo,e.unidade,i.codigo,r.revisao,e.pagina
 from public.especificacoes_instrucao_trabalho e join public.revisoes_instrucao_trabalho r on r.id=e.revisao_id
 join public.instrucoes_trabalho i on i.id=r.instrucao_id
 where r.status='VIGENTE' and e.conferido and e.chave_parametro=upper(trim(p_chave))
  and (e.produto_id is null or e.produto_id=p_produto_id)
  and (e.equipamento is null or upper(e.equipamento)=upper(p_equipamento))
 order by (e.produto_id is not null) desc,(e.equipamento is not null) desc,r.vigente_em desc limit 1
$$;

