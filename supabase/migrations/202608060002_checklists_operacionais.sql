insert into public.itens_checklist(
  modelo_id,codigo,secao,descricao,tipo_resposta,unidade,valor_minimo,valor_alvo,
  valor_maximo,permite_na,critico,gera_carta,plano_reacao,ordem
)
select model.id,item.codigo,item.secao,item.descricao,item.tipo,item.unidade,
  item.minimo::numeric,item.alvo::numeric,item.maximo::numeric,
  item.permite_na,item.critico,item.carta,item.reacao,item.ordem
from item_data item join public.modelos_checklist model on model.codigo=item.modelo
on conflict(modelo_id,codigo) do update set
  secao=excluded.secao,descricao=excluded.descricao,tipo_resposta=excluded.tipo_resposta,
  unidade=excluded.unidade,valor_minimo=excluded.valor_minimo,valor_alvo=excluded.valor_alvo,
