create or replace function public.usuario_tem_permissao_checklist(p_codigo text)
returns boolean language sql stable security definer
set search_path=pg_catalog,public as $$
  select auth.uid() is not null and coalesce(
    (select user_permission.permitido
     from public.usuario_permissoes user_permission
     join public.permissoes permission on permission.id=user_permission.permissao_id
     where user_permission.usuario_id=auth.uid()
       and permission.codigo=p_codigo limit 1),
    exists(select 1 from public.usuario_perfis user_profile
      join public.perfil_permissoes profile_permission
        on profile_permission.perfil_id=user_profile.perfil_id
      join public.permissoes permission
        on permission.id=profile_permission.permissao_id
      where user_profile.usuario_id=auth.uid() and permission.codigo=p_codigo),
    false
  );
$$;

grant execute on function public.usuario_tem_permissao_checklist(text) to authenticated;

create table if not exists public.areas_checklist (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nome text not null,
  ordem integer not null default 0,
  cor text not null default '#1f45a8',
  ativo boolean not null default true
);

create table if not exists public.modelos_checklist (
  id bigint generated by default as identity primary key,
  area_id bigint not null references public.areas_checklist(id),
  codigo text not null unique,
  nome text not null,
  descricao text,
  instrucao_codigo text,
  instrucao_revisao text,
  frequencia_tipo text not null check(frequencia_tipo in(
    'INICIO_TURNO','SETUP','INTERVALO','CORRIDA','DIARIO','SEMANAL','EVENTO','ESPECIAL'
  )),
  intervalo_minutos integer check(intervalo_minutos is null or intervalo_minutos>0),
  produto_obrigatorio boolean not null default false,
  equipamento_obrigatorio boolean not null default false,
  corrida_obrigatoria boolean not null default false,
  versao integer not null default 1,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.itens_checklist (
  id bigint generated by default as identity primary key,
  modelo_id bigint not null references public.modelos_checklist(id) on delete cascade,
  codigo text not null,
  secao text not null default 'Verificações',
  descricao text not null,
  orientacao text,
  tipo_resposta text not null default 'CONFORMIDADE' check(tipo_resposta in(
    'CONFORMIDADE','NUMERO','TEXTO','SIM_NAO'
  )),
  unidade text,
  valor_minimo numeric,
  valor_alvo numeric,
  valor_maximo numeric,
  permite_na boolean not null default false,
  critico boolean not null default false,
  gera_carta boolean not null default false,
  plano_reacao text,
  ordem integer not null default 0,
  ativo boolean not null default true,
  unique(modelo_id,codigo)
