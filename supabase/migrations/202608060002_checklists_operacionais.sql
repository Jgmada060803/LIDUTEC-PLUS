create table if not exists public.execucoes_checklist (
  id bigint generated by default as identity primary key,
  modelo_id bigint not null references public.modelos_checklist(id),
  data_operacional date not null default current_date,
  turno text not null check(turno in('MANHA','TARDE','NOITE')),
  produto_id bigint references public.produtos(id),
  equipamento text,
